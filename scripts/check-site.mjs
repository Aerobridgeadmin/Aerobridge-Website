import { access, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dashboardRoot = resolve(root, '..', 'aerobridge')

const pages = new Map([
  ['/', 'index.html'],
  ['/about', 'about.html'],
  ['/contact', 'contact.html'],
  ['/exam-preparation', 'exam-preparation.html'],
  ['/faq', 'faq.html'],
  ['/free-consultation', 'free-consultation.html'],
  ['/get-started', 'get-started.html'],
  ['/history', 'history.html'],
  ['/pricing', 'pricing.html'],
  ['/services', 'services.html'],
])

const forbidden = [
  ['em dash', '—'],
  ['legacy Bootstrap dependency', 'bootstrap'],
  ['broken consultation API', '/api/available-slots'],
  ['old consultation API', '/api/create-consultation'],
  ['legacy floating WhatsApp control', 'whatsapp-float'],
  ['Spanish booking copy', 'Sin horarios'],
  ['Spanish pricing copy', 'Pricing y'],
  ['inline style attribute', ' style='],
]

function count(text, needle) {
  return text.split(needle).length - 1
}

function fail(message) {
  throw new Error(message)
}

const htmlByRoute = new Map()
for (const [route, filename] of pages) {
  const html = await readFile(resolve(root, filename), 'utf8')
  htmlByRoute.set(route, html)

  if (!html.includes('Generated by scripts/build-site.mjs')) fail(`${filename}: missing generated-file marker`)
  if (!html.includes('<html lang="en">')) fail(`${filename}: document language is not English`)
  if (!html.includes('/assets/site.css')) fail(`${filename}: shared stylesheet missing`)
  if (!html.includes('/assets/site.js')) fail(`${filename}: shared script missing`)
  if (count(html, '<header class="site-header">') !== 1) fail(`${filename}: expected one shared header`)
  if (count(html, '<footer class="site-footer">') !== 1) fail(`${filename}: expected one shared footer`)
  if (count(html, '<main id="main-content">') !== 1) fail(`${filename}: expected one main region`)
  if (!html.includes('+56 9 7398 0874')) fail(`${filename}: canonical phone number missing`)
  if (html.includes('AeroBridge')) fail(`${filename}: old brand spelling found`)

  for (const [label, text] of forbidden) {
    if (html.toLowerCase().includes(text.toLowerCase())) fail(`${filename}: ${label} found`)
  }

  const hrefs = [...html.matchAll(/href="(\/[^"]*)"/g)].map((match) => match[1].split(/[?#]/)[0])
  for (const href of hrefs) {
    if (href.startsWith('/assets/')) continue
    if (!pages.has(href)) fail(`${filename}: internal link has no generated page: ${href}`)
  }
}

const stylesheet = await readFile(resolve(root, 'assets/site.css'), 'utf8')
const clientScript = await readFile(resolve(root, 'assets/site.js'), 'utf8')
if (stylesheet.includes('linear-gradient') || stylesheet.includes('radial-gradient')) fail('site.css: gradients are not part of the restrained visual system')
if (stylesheet.includes('@keyframes')) fail('site.css: ambient template animations are not allowed')
if (!clientScript.includes('data-consultation-form')) fail('site.js: working consultation handoff is missing')

try {
  await access(resolve(dashboardRoot, 'src/lib/programs.data.json'))
  const dashboardPrograms = JSON.parse(await readFile(resolve(dashboardRoot, 'src/lib/programs.data.json'), 'utf8'))
  const dashboardPacks = JSON.parse(await readFile(resolve(dashboardRoot, 'src/lib/country-packs.data.json'), 'utf8'))
  const englishCurriculum = JSON.parse(await readFile(resolve(dashboardRoot, 'src/lib/curriculum.data.json'), 'utf8'))
  const englishLessons = JSON.parse(await readFile(resolve(dashboardRoot, 'src/lib/lessons.data.json'), 'utf8'))

  const requiredPrograms = [
    'ICAO Aviation English',
    'Pilot Licence Theory',
    'Air Traffic Controller Knowledge',
    'Maintenance Personnel Licensing',
    'Flight Dispatch Knowledge',
    'Cabin Crew Safety',
    'UAS and RPAS Operations',
  ]
  const manifestTitles = dashboardPrograms.map((program) => program.title)
  for (const program of requiredPrograms) {
    if (!manifestTitles.includes(program)) fail(`dashboard manifest no longer contains expected program: ${program}`)
  }
  const available = dashboardPrograms.filter((program) => program.status === 'available').map((program) => program.title)
  if (available.join('|') !== 'ICAO Aviation English|Pilot Licence Theory') fail(`available programs changed: ${available.join(', ')}`)
  const beta = dashboardPrograms.filter((program) => program.releaseStage === 'beta').map((program) => program.title)
  if (beta.join('|') !== 'Pilot Licence Theory') fail(`beta programs changed: ${beta.join(', ')}`)

  const countryCodes = dashboardPacks.map((pack) => pack.iso2)
  if (countryCodes.join(',') !== 'CL') fail(`marketing country scope is stale; dashboard packs are now: ${countryCodes.join(', ')}`)
  const chile = dashboardPacks[0]
  if (chile.lastVerifiedAt !== '2026-07-11') fail(`Chile verification date changed in dashboard manifest: ${chile.lastVerifiedAt}`)
  if (englishCurriculum.modules.length !== 6) fail(`Aviation English module count changed to ${englishCurriculum.modules.length}`)
  if (englishLessons.length !== 30) fail(`Aviation English lesson count changed to ${englishLessons.length}`)
} catch (error) {
  if (error && error.code === 'ENOENT') {
    console.warn('Dashboard source not found beside the website. Cross-repo truth checks skipped.')
  } else {
    throw error
  }
}

console.log(`Checked ${pages.size} pages, shared assets, links and dashboard catalog alignment.`)
